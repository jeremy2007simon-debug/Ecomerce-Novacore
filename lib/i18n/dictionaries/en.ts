/**
 * Widen the literal types produced by `as const` to `string`, while keeping the
 * KEY structure exact.
 *
 * Without this, `const es: Dictionary` would demand that the Spanish nav label
 * be literally the string "Shop". With it, the compiler enforces precisely what
 * we want it to enforce: every key present, no key invented, values free.
 */
type Translations<T> = {
  [K in keyof T]: T[K] extends string ? string : Translations<T[K]>;
};

export type Dictionary = Translations<typeof en>;

/** The subset handed to client islands. Kept separate so it stays small. */
export type ClientDictionary = Dictionary['client'];
export type ServerDictionary = Dictionary['server'];
